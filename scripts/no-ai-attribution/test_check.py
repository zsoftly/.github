class OffendingLines(unittest.TestCase):
    def test_blocked(self):
        for line in BLOCKED:
            with self.subTest(line=line):
                self.assertEqual(offending_lines(f"Subject\n\nBody\n\n{line}\n"), [line.strip()])

    def test_allowed(self):
        for line in ALLOWED:
            with self.subTest(line=line):
                self.assertEqual(offending_lines(f"Subject\n\n{line}\n"), [])

    def test_none_body(self):
        self.assertEqual(offending_lines(None), [])


if __name__ == "__main__":
    unittest.main()
