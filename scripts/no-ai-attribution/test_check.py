class OffendingLines(unittest.TestCase):
    def test_blocked(self):
        for line in BLOCKED:
            with self.subTest(line=line):
                self.assertEqual(offending_lines(f"Subject\n\nBody\n\n{line}\n"), [line.strip()])

    def test_allowed(self):
        for line in ALLOWED:
            with self.subTest(line=line):
                self.assertEqual(offending_lines(f"Subject\n\n{line}\n"), [])

    def test_ai_author_or_committer(self):
        human = {"name": "Jane Doe", "email": "jane@zsoftly.com"}
        web = {"name": "GitHub", "email": "noreply@github.com"}
        ai = {"name": "Claude", "email": "noreply@anthropic.com"}
        self.assertEqual(commit_findings({"message": "Fix", "author": human, "committer": web}), [])
        self.assertEqual(len(commit_findings({"message": "Fix", "author": ai, "committer": web})), 1)

    def test_message_file_skips_comments_and_diff(self):
        text = "Fix\n# Co-authored-by: Claude\n# ------------------------ >8 ------------------------\n+noreply@anthropic.com\n"
        with tempfile.NamedTemporaryFile("w", delete=False, encoding="utf-8") as f:
            f.write(text)
        try:
            self.assertEqual(offending_lines(message_file(f.name)), [])
        finally:
            os.unlink(f.name)

    def test_none_body(self):
        self.assertEqual(offending_lines(None), [])


if __name__ == "__main__":
    unittest.main()
